// Pure functions for the shared control contract (no file I/O; generate.mjs does the reading
// and writing). The Windows registry export (control.manifest.json) is the authoring source;
// control.platforms.json says, per action and per feedback field, whether macOS answers it.
// Plan: docs/superpowers/plans/2026-11-16-mac-remote-control-phase1.md (Task 2).

const MAC_VALUES = ['supported', 'blocked', 'notApplicable'];
const PARAM_TYPES = ['string', 'int', 'double', 'bool'];

function fail(message) {
  throw new Error(`control.platforms.json: ${message}`);
}

function checkRow(row, name, workstreams) {
  if (!MAC_VALUES.includes(row.mac)) fail(`${name}: mac must be one of ${MAC_VALUES.join('|')} (got ${JSON.stringify(row.mac)})`);
  const hasBlockedOn = Object.hasOwn(row, 'blockedOn');
  const hasReason = Object.hasOwn(row, 'reason');
  if (row.mac === 'supported') {
    if (hasBlockedOn || hasReason) fail(`${name}: a supported row carries no blockedOn or reason`);
  } else if (row.mac === 'blocked') {
    if (!hasBlockedOn || !Object.hasOwn(workstreams, row.blockedOn)) {
      fail(`${name}: blockedOn must name a workstream (got ${JSON.stringify(row.blockedOn)})`);
    }
    if (hasReason) fail(`${name}: a blocked row's sentence comes from its workstream label, not a reason`);
  } else {
    if (typeof row.reason !== 'string' || !row.reason.trim()) fail(`${name}: notApplicable needs a non-blank reason`);
    if (hasBlockedOn) fail(`${name}: notApplicable has no blockedOn`);
  }
}

// One row per expected key, in the expected order. Rows are arrays, so a duplicate is visible.
function checkCoverage(rows, key, expected, what) {
  const seen = new Set();
  for (const row of rows) {
    if (seen.has(row[key])) fail(`${row[key]} appears twice in ${what}`);
    seen.add(row[key]);
  }
  const missing = expected.filter(id => !seen.has(id));
  if (missing.length) fail(`no macOS row in ${what} for ${missing.join(', ')}`);
  const unknown = rows.map(r => r[key]).filter(id => !expected.includes(id));
  if (unknown.length) fail(`${what} rows name nothing in control.manifest.json: ${unknown.join(', ')}`);
  rows.forEach((row, i) => {
    if (row[key] !== expected[i]) fail(`${what} must follow control.manifest.json order: row ${i} is ${row[key]}, expected ${expected[i]}`);
  });
}

/** Throws Error(message) on the first violation; messages start with `control.platforms.json:`. */
export function validatePlatforms(manifest, platforms) {
  if (!platforms || typeof platforms !== 'object') fail('not an object');
  const workstreams = platforms.workstreams;
  if (!workstreams || typeof workstreams !== 'object' || Array.isArray(workstreams)) fail('workstreams must be an object');
  for (const [code, label] of Object.entries(workstreams)) {
    if (typeof label !== 'string' || !label.trim()) fail(`workstream ${code} needs a non-blank label`);
  }
  if (!Array.isArray(platforms.actions)) fail('actions must be an array');
  if (!Array.isArray(platforms.feedbackFields)) fail('feedbackFields must be an array');
  for (const row of platforms.actions) checkRow(row, row.id, workstreams);
  for (const row of platforms.feedbackFields) checkRow(row, row.field, workstreams);
  checkCoverage(platforms.actions, 'id', manifest.Actions.map(a => a.Id), 'actions');
  checkCoverage(platforms.feedbackFields, 'field', manifest.FeedbackFields, 'feedbackFields');
}

/** A Swift string literal, quotes included. A backslash is always doubled first, so `\(` never appears. */
export function swiftString(text) {
  let out = '"';
  for (const ch of String(text)) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20) out += `\\u{${code.toString(16).toUpperCase()}}`;
    else out += ch;
  }
  return out + '"';
}

function availability(row, workstreams) {
  if (row.mac === 'supported') return '.supported';
  if (row.mac === 'blocked') {
    return `.blocked(workstream: ${swiftString(row.blockedOn)}, label: ${swiftString(workstreams[row.blockedOn])})`;
  }
  return `.notApplicable(reason: ${swiftString(row.reason)})`;
}

/** The generated Swift file as lines (no trailing "\n"). Validate first; this assumes a valid pair. */
export function generateControlSwift(manifest, platforms) {
  const rows = new Map(platforms.actions.map(r => [r.id, r]));
  const lines = [
    '// GENERATED by contracts/generate.mjs from contracts/control.manifest.json and',
    '// contracts/control.platforms.json. Do not edit; run `npm run contract:generate`.',
    '',
    'enum ControlMacAvailability: Equatable {',
    '    case supported',
    '    case blocked(workstream: String, label: String)',
    '    case notApplicable(reason: String)',
    '}',
    '',
    'struct ControlManifestEntry {',
    '    let action: ControlAction',
    '    let availability: ControlMacAvailability',
    '}',
    '',
    'enum ControlManifestGenerated {',
    `    static let version = ${Number(manifest.Version)}`,
    `    static let root = ${swiftString(manifest.Root)}`,
    '    static let entries: [ControlManifestEntry] = [',
  ];
  for (const action of manifest.Actions) {
    const head = `            action: ControlAction(id: ${swiftString(action.Id)}, title: ${swiftString(action.Title)}, `
      + `description: ${swiftString(action.Description)}, params: `;
    lines.push('        ControlManifestEntry(');
    if (!action.Params.length) {
      lines.push(head + '[]),');
    } else {
      lines.push(head + '[');
      for (const param of action.Params) {
        if (!PARAM_TYPES.includes(param.Type)) {
          throw new Error(`control.manifest.json: unsupported param type '${param.Type}' on ${action.Id}`);
        }
        const description = param.Description == null ? 'nil' : swiftString(param.Description);
        lines.push(`                ControlParam(name: ${swiftString(param.Name)}, type: .${param.Type}, `
          + `required: ${param.Required ? 'true' : 'false'}, description: ${description}),`);
      }
      lines.push('            ]),');
    }
    const row = rows.get(action.Id);
    if (!row) throw new Error(`control.platforms.json: no macOS row for ${action.Id}`);
    lines.push(`            availability: ${availability(row, platforms.workstreams)}),`);
  }
  lines.push('    ]');
  lines.push('    static let feedbackFields: [(field: String, availability: ControlMacAvailability)] = [');
  for (const row of platforms.feedbackFields) {
    lines.push(`        (${swiftString(row.field)}, ${availability(row, platforms.workstreams)}),`);
  }
  lines.push('    ]', '}');
  return lines;
}
